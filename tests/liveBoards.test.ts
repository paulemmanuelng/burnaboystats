/**
 * The artwork floor ("resolves artwork for most releases") is skipped in ONE
 * place: the Stats live publishing gate (.github/workflows/stats-live.yml,
 * "Verify the regenerated data", PUBLISH_GATE=1), the same way the deadline
 * alarms in tests/awardsPending.test.ts and the rest are.
 *
 * A missing sleeve is decoration: the row draws its monogram. But on that path
 * a red here stops the commit step, so nothing on the site publishes. Fireboy
 * DML's new album (16 Oct 2026) left ten tracks without a Deezer sleeve, and
 * from 21:12 UTC that day no run published a figure: not his board, not Burna
 * Boy's career streams, not Dai Dai. The floor still fails in ci.yml on every
 * push and pull request, which is where a human reads it.
 *
 * Only the floor. The https check on every cover that IS set, and every other
 * test in this file, still runs on the publishing path.
 */
const PUBLISHING_GATE = process.env.PUBLISH_GATE === "1";

// The board's live charts are generated by the same pipeline as Burna Boy's
// (scripts/build-live-charts.mjs --artist=<slug>) into a file of their own.
// These are the invariants a regenerated snapshot must keep — the data itself
// changes every hour, so nothing here pins a figure.
describe("the board's live charts", () => {
  it("belongs to an artist who is actually on the board", () => {
    for (const b of LIVE_BOARDS) expect(artistBySlug(b.slug), b.slug).toBeTruthy();
  });

  // Until 25 Sep 2026 this was one test, "is never empty, and never Burna Boy's
  // data". Since the per-artist floor, an artist declared `mayChartNowhere`
  // has a floor of 0 and may hold no placement and no release on a given day,
  // so "never empty" was no longer what it checked. Split in two, each named
  // for what it holds.
  it("clears its artist's placement floor, so it is empty only for an artist declared mayChartNowhere", () => {
    for (const b of LIVE_BOARDS) {
      // The floor is an "is this file real" check, not a quality bar, so it
      // cannot be one number for everyone: an artist whose breakout is years
      // old genuinely holds almost no live placement. Rather than pick a
      // second number here, read the SAME rule the build script uses —
      // placementFloor() in scripts/live-artists.mjs — so the two cannot drift.
      const floor = placementFloor(LIVE_REGISTRY[b.slug] ?? { slug: b.slug });
      expect(b.placements, b.slug).toBeGreaterThanOrEqual(floor);
      // A full-size board carries a real catalogue; a small one (a lowered
      // floor) may hold a handful of releases, and one that may chart nowhere
      // may hold none on a given day.
      const minReleases = floor >= 25 ? 6 : floor > 0 ? 1 : 0;
      expect(b.releases.length, b.slug).toBeGreaterThanOrEqual(minReleases);
      // Every other board is never empty.
      if (floor > 0) expect(b.placements, b.slug).toBeGreaterThan(0);
    }
  });

  it("names the boards allowed to be empty, so that list cannot grow unseen", () => {
    // A floor of 0 is a declaration in scripts/live-artists.mjs, not a
    // default. These are the live boards carrying it on 25 Sep 2026; adding
    // one here is a deliberate edit, the same as adding it there.
    const mayBeEmpty = LIVE_BOARDS.filter((b) => placementFloor(LIVE_REGISTRY[b.slug] ?? { slug: b.slug }) === 0)
      .map((b) => b.slug)
      .sort();
    expect(mayBeEmpty).toEqual(["black-sherif", "bnxn", "ckay", "olamide", "oxlade", "tiwa-savage"]);
  });

  it("is never Burna Boy's data", () => {
    for (const b of LIVE_BOARDS) {
      // The bug this guards: one shared module-level fetch cache used to mean
      // a second artist's page could render Burna Boy's snapshot.
      const shared = b.releases.filter((r) => burnaLive.some((x) => x.title === r.title));
      if (b.releases.length > 0) {
        expect(shared.length, `${b.slug} shares ${shared.length} titles with Burna Boy`).toBeLessThan(
          b.releases.length / 2
        );
      }
    }
  });

  it("counts its own totals from its own rows", () => {
    for (const b of LIVE_BOARDS) {
      const entries = b.releases.flatMap((r) => r.platforms.flatMap((p) => p.entries));
      expect(b.placements, b.slug).toBe(entries.length);
      // Counted the way the page counts them: "UK" and "GB" are one country
      // and "WW" is none, so the raw code set is an upper bound.
      expect(b.countries, b.slug).toBe(countriesOf(entries));
      expect(b.countries, b.slug).toBeLessThanOrEqual(new Set(entries.map((e) => e.country)).size);
      expect(b.platformTotals.reduce((n, p) => n + p.placements, 0), b.slug).toBe(entries.length);
    }
  });

  it("never lists the same country twice inside one platform", () => {
    for (const b of LIVE_BOARDS)
      for (const r of b.releases)
        for (const p of r.platforms) {
          const codes = p.entries.map((e) => e.country);
          expect(new Set(codes).size, `${b.slug} → ${r.title} → ${p.platform}`).toBe(codes.length);
        }
  });

  // "Kese" and "Kese (Dance)", "Wa" and "Wa (Live)", "Ako" and "Ako - Live in
  // London": one record under two names, the same chart row counted twice,
  // until scripts/live-artists.mjs learned the alias. Titles alone are a weak
  // test — this checks the thing that is actually wrong, two releases holding
  // the SAME position on the SAME chart. Song and album charts are separate
  // charts, so a song and an album may share a position legitimately.
  it("never counts one chart row under two titles", () => {
    for (const b of LIVE_BOARDS) {
      const seen = new Map<string, Set<string>>();
      for (const r of b.releases)
        for (const p of r.platforms)
          for (const e of p.entries) {
            const key = `${r.kind}|${p.platform}|${e.country}|${e.position}`;
            if (!seen.has(key)) seen.set(key, new Set());
            seen.get(key)!.add(r.title);
          }
      const clashes = [...seen.entries()]
        .filter(([, titles]) => titles.size > 1)
        .map(([key, titles]) => `${key}: ${[...titles].join(" / ")}`);
      expect(clashes, b.slug).toEqual([]);
    }
  });

  it.skipIf(PUBLISHING_GATE)("resolves artwork for most releases", () => {
    // The bar is a floor, not a knife edge. It used to be `> 0.8`, and Black
    // Sherif sat on exactly 0.8 for two days: the board is rebuilt hourly, so
    // the ratio's denominator moves, and the same data failed CI while passing
    // locally. Every stats run was blocked by a strict inequality against a
    // number the pipeline lands on legitimately.
    //
    // The failure also has to be actionable. Coverage alone says a board is
    // short without saying of what, and the cause here was a real one — six
    // FEATURED records, which Deezer bills to their lead artist, so the cover
    // lookup could not match them until it learned to read the credit list.
    //
    // Counted in whole releases, by the rule the builder logs against
    // (maxUnresolvedArt in scripts/live-artists.mjs): 80% from five releases
    // up, one monogram on a smaller board. As a bare ratio, 0.8 of four
    // releases was 100%, and an empty board was 0/0.
    //
    // A release new to the board is not judged until it is older than
    // NEW_RELEASE_ART_GRACE_DAYS, counted from its firstSeen to the board's
    // own liveChartsUpdated (artFloor, the same rule the builder logs).
    for (const b of LIVE_BOARDS) {
      const floor = artFloor(b.releases, b.updated);
      expect(
        floor.counted.length,
        `${b.slug} artwork: ${b.releases.length - floor.unresolved.length}/${b.releases.length} — unresolved: ${floor.unresolved.join(", ") || "none"}` +
          (floor.inGrace.length ? ` (still in new-release grace: ${floor.inGrace.join(", ")})` : "")
      ).toBeLessThanOrEqual(floor.allowed);
    }
  });

  // Split out of the floor above on 18 Oct 2026, so the publishing gate can
  // skip the floor and keep this. A sleeve that is set is shipped to every
  // reader, so it is held on every path.
  it("serves every cover it does carry over https", () => {
    for (const b of LIVE_BOARDS)
      for (const r of b.releases.filter((r) => r.cover)) {
        expect(r.cover, `${b.slug} → ${r.title}`).toMatch(/^https:\/\//);
      }
  });

  it("holds every board of five or more releases to exactly the 80% floor", () => {
    // The allowance must not loosen the floor for a real catalogue. Checked
    // in integers: (n - m) / n >= 0.8 is 5(n - m) >= 4n.
    for (let n = 5; n <= 200; n++)
      for (let m = 0; m <= n; m++)
        expect(m <= maxUnresolvedArt(n), `${m} of ${n} unresolved`).toBe(5 * (n - m) >= 4 * n);
  });

  it("lets a small board carry one monogram, and an empty one pass", () => {
    // Oxlade's board on the 6 Oct 2026 runs (00:05, 06:24 and 18:24 UTC), as
    // the build logged it: "artwork: 3/4 releases — unresolved: Eclipse - EP".
    // 0.75 against 0.8 failed verification, and none of the three runs
    // published a figure.
    const oct6 = { releases: 4, unresolved: ["Eclipse - EP"] };
    expect(oct6.unresolved.length).toBeLessThanOrEqual(maxUnresolvedArt(oct6.releases));
    // Two misses on the same board are still a failure.
    expect(2).toBeGreaterThan(maxUnresolvedArt(oct6.releases));
    // A board declared mayChartNowhere may hold no release on a given day.
    expect(0).toBeLessThanOrEqual(maxUnresolvedArt(0));
    for (const n of [1, 2, 3, 4]) expect(maxUnresolvedArt(n), `${n} releases`).toBe(1);
  });

  it("searches Deezer for a sleeve without Apple's ' - EP' / ' - Single' suffix", () => {
    // The twelve " - EP" titles left unresolved on the 6 Oct 2026 18:24 UTC
    // run (REAL, Vol. 1 on two boards, so 13 rows), and "WWP - Single", left
    // unresolved on the 7 Oct 06:03 UTC run, as kworb's Apple album charts
    // print them. Deezer names these records without the storefront suffix,
    // so `album:"Eclipse - EP"` matched nothing.
    const apple: [string, string][] = [
      ["Eclipse - EP", "Eclipse"],
      ["REAL, Vol. 1 - EP", "REAL, Vol. 1"],
      ["RAVAGE - EP", "RAVAGE"],
      ["If Orange Was A Place - EP", "If Orange Was A Place"],
      ["Get Layd - EP", "Get Layd"],
      ["What Have We Done - EP", "What Have We Done"],
      ["CKay The Second - EP", "CKay The Second"],
      ["SUN SHERIF - EP", "SUN SHERIF"],
      ["Still In Charge - EP", "Still In Charge"],
      ["The Game Needs Us - EP", "The Game Needs Us"],
      ["Nahamciaga - EP", "Nahamciaga"],
      ["PANDEMIC - EP", "PANDEMIC"],
      ["WWP - Single", "WWP"],
    ];
    for (const [title, deezer] of apple) expect(coverSearchTitle(title), title).toBe(deezer);

    // Still strips the featured credit, as the inline expression it replaces
    // did. A zero-width space before the credit now goes too; the old
    // expression left it on the end. Titles are already cleaned when parsed
    // (stripInvisible), so this is a second guard, not a live change.
    expect(coverSearchTitle("Getting Paid ​(feat. Asake, Wizkid, Skillibeng)")).toBe("Getting Paid");
    expect(coverSearchTitle("Secondhand (feat. Rema) - Single")).toBe("Secondhand");

    // A version named after a dash is part of the title, not a storefront
    // suffix. Neither is a word that merely ends in "EP", or "EP" without a dash.
    for (const kept of [
      "KU LO SA - A COLORS SHOW",
      "Ako - Live in London",
      "Apple Music Live: Wizkid",
      "Vibez Incorporation Mixtape, Vol. 1",
      "Deep",
      "The EP",
      "Single",
      "Ololade Asake - EPilogue",
    ])
      expect(coverSearchTitle(kept), kept).toBe(kept);
  });

  it("builds its Deezer cover query from coverSearchTitle", () => {
    // The helper is only a fix if the builder calls it. An inline title regex
    // there is how the suffix went unseen.
    const src = readFileSync(join(process.cwd(), "scripts/build-live-charts.mjs"), "utf8");
    expect(src).toMatch(/const base = coverSearchTitle\(r\.title\);/);
  });

  it("logs, stamps and dates the artwork floor by the rule this file reads", () => {
    // The grace is only real if the generated file carries what the test
    // measures it with: firstSeen on every row of a board that resolves
    // artwork, stamped from the previous file by the cover carry's own key,
    // and a liveChartsUpdated from the same date a new row is stamped with.
    const src = readFileSync(join(process.cwd(), "scripts/build-live-charts.mjs"), "utf8");
    expect(src).toMatch(/const floor = artFloor\(releases, snapshotDate\);/);
    expect(src).toMatch(/stampFirstSeen\(releases, previous, snapshotDate\);/);
    expect(src).toMatch(/const coverKey = releaseKey;/);
    expect(src).toMatch(/export const liveChartsUpdated = \$\{JSON\.stringify\(snapshotDate\)\};/);
    expect(src).toMatch(/^\s*firstSeen\?: string;$/m);
    // The builder may not keep a floor of its own beside the shared one.
    expect(src).not.toMatch(/maxUnresolvedArt\(/);
  });

  it("wears no sleeve Deezer has blanked", () => {
    // 6ddb34c2… sat on Wizkid's "Superstar" until 24 Sep 2026. Deezer's CDN
    // answers it with a 302 to d41d8cd9… (the empty-string MD5), a grey
    // placeholder, and the builder's carry-forward kept it on every run. It
    // was never the album's sleeve either: an edge that still held the file
    // served DJ Xclusive's "Gal Badi" single, on which Wizkid features.
    const BLANKED = ["6ddb34c26029baeb2bd73c71bb8d839f", "d41d8cd98f00b204e9800998ecf8427e"];
    const offenders = LIVE_BOARDS.flatMap((b) =>
      b.releases
        .filter((r) => BLANKED.some((h) => r.cover?.includes(h)))
        .map((r) => `${b.slug}: ${r.title}`)
    );
    expect(offenders, "these rows render a grey square").toEqual([]);
  });

  it("gives Wizkid's Superstar its own EME sleeve", () => {
    // Deezer does not carry the 2011 album at all; Apple does (collection
    // 1627794779, ℗ Empire Mates Entertainment, 17 tracks from "Say My Name"
    // to "Wiz Party"), and the board's catalogue (app/data/afrobeats.ts)
    // already uses Apple's art. The builder's carry-forward keeps it from run
    // to run. A row with no cover renders the monogram, which is not wrong;
    // any other sleeve is.
    const superstar = liveBoardFor("wizkid")?.releases.find((r) => r.title === "Superstar");
    if (!superstar?.cover) return;
    expect(superstar.cover).toBe(
      "https://is1-ssl.mzstatic.com/image/thumb/Music112/v4/73/bd/59/73bd5950-72b7-8758-e91f-b2a16d558c57/0.jpg/300x300bb.jpg"
    );
  });

  it("points its country panels at its own endpoint", () => {
    for (const b of LIVE_BOARDS) expect(b.api).toBe(`/api/v1/live-charts/${b.slug}`);
  });

  it("is in the sitemap and the search index", async () => {
    const routes = (await sitemap()).map((e) => e.url);
    const paths = new Set(searchIndex.map((d) => d.path));
    for (const b of LIVE_BOARDS) {
      expect(routes.some((u) => u.endsWith(`/afrobeats/${b.slug}/live`)), b.slug).toBe(true);
      expect(paths.has(`/afrobeats/${b.slug}/live`), b.slug).toBe(true);
    }
  });

  it("covers every artist on the board, and nobody else", () => {
    // A live board needs no register sweep — the platform charts are readable
    // today — so the pending three have one as well.
    expect(LIVE_BOARDS.map((b) => b.slug).sort()).toEqual(afrobeatsSlugs.slice().sort());
    expect(hasLiveBoard("wizkid")).toBe(true);
    expect(hasLiveBoard("seyi-vibez")).toBe(true);
    // Burna Boy's live charts are the site's own page, not a board entry.
    expect(hasLiveBoard("burna-boy")).toBe(false);
    expect(liveBoardFor("nobody")).toBeUndefined();
  });
});

