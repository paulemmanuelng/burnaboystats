import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { LIVE_BOARDS, liveBoardFor, hasLiveBoard } from "../app/data/liveBoards";
import { liveCharts as burnaLive } from "../app/data/liveCharts";
import { artistBySlug, afrobeatsSlugs } from "../app/data/afrobeats";
import { countriesOf } from "../app/lib/liveChartMeta";
import sitemap from "../app/sitemap";
import { searchIndex } from "../app/lib/searchIndex";
// @ts-expect-error — plain .mjs registry shared with the build script
import { LIVE_ARTISTS as LIVE_REGISTRY, placementFloor, dropRefusal } from "../scripts/live-artists.mjs";

// The board's live charts are generated by the same pipeline as Burna Boy's
// (scripts/build-live-charts.mjs --artist=<slug>) into a file of their own.
// These are the invariants a regenerated snapshot must keep — the data itself
// changes every hour, so nothing here pins a figure.
describe("the board's live charts", () => {
  it("belongs to an artist who is actually on the board", () => {
    for (const b of LIVE_BOARDS) expect(artistBySlug(b.slug), b.slug).toBeTruthy();
  });

  it("is never empty, and never Burna Boy's data", () => {
    for (const b of LIVE_BOARDS) {
      // The floor is an "is this file real" check, not a quality bar, so it
      // cannot be one number for everyone: an artist whose breakout is years
      // old genuinely holds almost no live placement. Rather than pick a
      // second number here, read the SAME rule the build script uses —
      // placementFloor() in scripts/live-artists.mjs — so the two cannot drift.
      const floor = placementFloor(LIVE_REGISTRY[b.slug] ?? { slug: b.slug });
      expect(b.placements, b.slug).toBeGreaterThanOrEqual(floor);
      // A full-size board carries a real catalogue; a small one (a lowered
      // floor) may hold a handful of releases, and one that may chart nowhere
      // may hold none on a given day.
      const minReleases = floor >= 25 ? 6 : floor > 0 ? 1 : 0;
      expect(b.releases.length, b.slug).toBeGreaterThanOrEqual(minReleases);
      // The bug this guards: one shared module-level fetch cache used to mean
      // a second artist's page could render Burna Boy's snapshot.
      const shared = b.releases.filter((r) => burnaLive.some((x) => x.title === r.title));
      if (b.releases.length > 0) {
        expect(shared.length, `${b.slug} shares ${shared.length} titles with Burna Boy`).toBeLessThan(
          b.releases.length / 2
        );
      }
    }
  });

  it("counts its own totals from its own rows", () => {
    for (const b of LIVE_BOARDS) {
      const entries = b.releases.flatMap((r) => r.platforms.flatMap((p) => p.entries));
      expect(b.placements, b.slug).toBe(entries.length);
      // Counted the way the page counts them: "UK" and "GB" are one country
      // and "WW" is none, so the raw code set is an upper bound.
      expect(b.countries, b.slug).toBe(countriesOf(entries));
      expect(b.countries, b.slug).toBeLessThanOrEqual(new Set(entries.map((e) => e.country)).size);
      expect(b.platformTotals.reduce((n, p) => n + p.placements, 0), b.slug).toBe(entries.length);
    }
  });

  it("never lists the same country twice inside one platform", () => {
    for (const b of LIVE_BOARDS)
      for (const r of b.releases)
        for (const p of r.platforms) {
          const codes = p.entries.map((e) => e.country);
          expect(new Set(codes).size, `${b.slug} → ${r.title} → ${p.platform}`).toBe(codes.length);
        }
  });

  // "Kese" and "Kese (Dance)", "Wa" and "Wa (Live)", "Ako" and "Ako - Live in
  // London": one record under two names, the same chart row counted twice,
  // until scripts/live-artists.mjs learned the alias. Titles alone are a weak
  // test — this checks the thing that is actually wrong, two releases holding
  // the SAME position on the SAME chart. Song and album charts are separate
  // charts, so a song and an album may share a position legitimately.
  it("never counts one chart row under two titles", () => {
    for (const b of LIVE_BOARDS) {
      const seen = new Map<string, Set<string>>();
      for (const r of b.releases)
        for (const p of r.platforms)
          for (const e of p.entries) {
            const key = `${r.kind}|${p.platform}|${e.country}|${e.position}`;
            if (!seen.has(key)) seen.set(key, new Set());
            seen.get(key)!.add(r.title);
          }
      const clashes = [...seen.entries()]
        .filter(([, titles]) => titles.size > 1)
        .map(([key, titles]) => `${key}: ${[...titles].join(" / ")}`);
      expect(clashes, b.slug).toEqual([]);
    }
  });

  it("resolves artwork for most releases", () => {
    // The bar is a floor, not a knife edge. It used to be `> 0.8`, and Black
    // Sherif sat on exactly 0.8 for two days: the board is rebuilt hourly, so
    // the ratio's denominator moves, and the same data failed CI while passing
    // locally. Every stats run was blocked by a strict inequality against a
    // number the pipeline lands on legitimately.
    //
    // The failure also has to be actionable. Coverage alone says a board is
    // short without saying of what, and the cause here was a real one — six
    // FEATURED records, which Deezer bills to their lead artist, so the cover
    // lookup could not match them until it learned to read the credit list.
    for (const b of LIVE_BOARDS) {
      const missing = b.releases.filter((r) => !r.cover).map((r) => r.title);
      const coverage = (b.releases.length - missing.length) / b.releases.length;
      expect(
        coverage,
        `${b.slug} artwork coverage — unresolved: ${missing.join(", ") || "none"}`
      ).toBeGreaterThanOrEqual(0.8);
      for (const r of b.releases.filter((r) => r.cover)) {
        expect(r.cover, `${b.slug} → ${r.title}`).toMatch(/^https:\/\//);
      }
    }
  });

  it("wears no sleeve Deezer has blanked", () => {
    // 6ddb34c2… sat on Wizkid's "Superstar" until 24 Sep 2026. Deezer's CDN
    // answers it with a 302 to d41d8cd9… (the empty-string MD5), a grey
    // placeholder, and the builder's carry-forward kept it on every run. It
    // was never the album's sleeve either: an edge that still held the file
    // served DJ Xclusive's "Gal Badi" single, on which Wizkid features.
    const BLANKED = ["6ddb34c26029baeb2bd73c71bb8d839f", "d41d8cd98f00b204e9800998ecf8427e"];
    const offenders = LIVE_BOARDS.flatMap((b) =>
      b.releases
        .filter((r) => BLANKED.some((h) => r.cover?.includes(h)))
        .map((r) => `${b.slug}: ${r.title}`)
    );
    expect(offenders, "these rows render a grey square").toEqual([]);
  });

  it("gives Wizkid's Superstar its own EME sleeve", () => {
    // Deezer does not carry the 2011 album at all; Apple does (collection
    // 1627794779, ℗ Empire Mates Entertainment, 17 tracks from "Say My Name"
    // to "Wiz Party"), and the board's catalogue (app/data/afrobeats.ts)
    // already uses Apple's art. The builder's carry-forward keeps it from run
    // to run. A row with no cover renders the monogram, which is not wrong;
    // any other sleeve is.
    const superstar = liveBoardFor("wizkid")?.releases.find((r) => r.title === "Superstar");
    if (!superstar?.cover) return;
    expect(superstar.cover).toBe(
      "https://is1-ssl.mzstatic.com/image/thumb/Music112/v4/73/bd/59/73bd5950-72b7-8758-e91f-b2a16d558c57/0.jpg/300x300bb.jpg"
    );
  });

  it("points its country panels at its own endpoint", () => {
    for (const b of LIVE_BOARDS) expect(b.api).toBe(`/api/v1/live-charts/${b.slug}`);
  });

  it("is in the sitemap and the search index", async () => {
    const routes = (await sitemap()).map((e) => e.url);
    const paths = new Set(searchIndex.map((d) => d.path));
    for (const b of LIVE_BOARDS) {
      expect(routes.some((u) => u.endsWith(`/afrobeats/${b.slug}/live`)), b.slug).toBe(true);
      expect(paths.has(`/afrobeats/${b.slug}/live`), b.slug).toBe(true);
    }
  });

  it("covers every artist on the board, and nobody else", () => {
    // A live board needs no register sweep — the platform charts are readable
    // today — so the pending three have one as well.
    expect(LIVE_BOARDS.map((b) => b.slug).sort()).toEqual(afrobeatsSlugs.slice().sort());
    expect(hasLiveBoard("wizkid")).toBe(true);
    expect(hasLiveBoard("seyi-vibez")).toBe(true);
    // Burna Boy's live charts are the site's own page, not a board entry.
    expect(hasLiveBoard("burna-boy")).toBe(false);
    expect(liveBoardFor("nobody")).toBeUndefined();
  });
});

// The credit matcher decides whose rows a swept country chart contributes, and
// a bare substring is not good enough: /rema/i matched "Reman - Ropero" and
// "La Suprema Corte - Porque Fallaste", so two Burkinabè songs and an
// Ecuadorian one shipped on Rema's live board.
describe("credit matchers", () => {
  it("is word-anchored for every artist", async () => {
    const { LIVE_ARTISTS } = await import("../scripts/live-artists.mjs");
    for (const [slug, a] of Object.entries(LIVE_ARTISTS)) {
      const src = (a as { credit: RegExp }).credit.source;
      expect(src.startsWith("\\b") && src.endsWith("\\b"), `${slug}: ${src}`).toBe(true);
    }
  });

  it("does not fire on a name that merely contains the artist's", async () => {
    const { LIVE_ARTISTS } = await import("../scripts/live-artists.mjs");
    const cases: [string, string, boolean][] = [
      ["Reman", "rema", false],
      ["La Suprema Corte", "rema", false],
      ["Rema", "rema", true],
      ["Rema & Selena Gomez", "rema", true],
      ["Systems", "tems", false],
      ["Tems", "tems", true],
      ["Tylan", "tyla", false],
      ["Tyla", "tyla", true],
      ["Davidson", "davido", false],
      ["Davido", "davido", true],
      ["WizKid", "wizkid", true],
      ["Burna Boy", "burna-boy", true],
      // The eight staged on 24 Sep 2026. Every string is a real credit: a
      // chart line kworb printed that day, or an artist profile on Deezer.
      ["21 Savage", "tiwa-savage", false],
      ["Savage Garden", "tiwa-savage", false],
      ["Spyro & Tiwa Savage", "tiwa-savage", true],
      ["Kiss Daniel", "kizz-daniel", true],
      ["Kizz Daniel & Tekno", "kizz-daniel", true],
      ["Kizzy Daniels", "kizz-daniel", false],
      ["Mr. Eazi", "mr-eazi", true],
      ["Eugy Official & Mr Eazi", "mr-eazi", true],
      ["Ruger Hauer", "ruger", false],
      ["Ruger", "ruger", true],
      ["Yo Maps & Stonebwoy", "stonebwoy", true],
      ["Yanga Chief, Oxlade & Thatohatsi", "oxlade", true],
      ["Yemi Alade", "yemi-alade", true],
      ["Sarkodie", "sarkodie", true],
    ];
    for (const [credit, slug, want] of cases)
      expect((LIVE_ARTISTS as Record<string, { credit: RegExp }>)[slug].credit.test(credit), `${credit} → ${slug}`).toBe(want);
  });
});

// The hourly job used to name all nine artists on its command line, which
// meant adding one to the registry silently left it un-refreshed. It passes
// "--artist=board" now; this holds the two ends together.
describe("the hourly refresh", () => {
  it("builds every board artist, and the registry matches the pages", async () => {
    const { LIVE_ARTISTS } = await import("../scripts/live-artists.mjs");
    // A `staged` artist is built but has no page yet, and "--artist=board"
    // skips it (build-live-charts.mjs), so it is outside both ends here too.
    const artists = LIVE_ARTISTS as Record<string, { staged?: boolean }>;
    const registry = Object.keys(artists)
      .filter((s) => s !== "burna-boy" && !artists[s].staged)
      .sort();
    expect(registry).toEqual(LIVE_BOARDS.map((b) => b.slug).sort());

    const workflow = readFileSync(join(process.cwd(), ".github/workflows/stats-live.yml"), "utf8");
    expect(workflow).toContain("build-live-charts.mjs --artist=board");
    // Burna Boy's own refresh must still run, and must run unqualified.
    expect(workflow).toMatch(/build-live-charts\.mjs\s*$/m);
  });
});

// The builder refuses to overwrite a snapshot when too much of it vanished at
// once (a half-scraped source). The rule has to hold on a 700-placement board
// and on a 4-placement one, so it is checked with the real sizes it meets.
describe("the live-charts drop rule", () => {
  it("still refuses a half-scraped big board", () => {
    // Burna Boy's file carries about 709 placements.
    expect(dropRefusal(709, 300)).toMatch(/58% drop/);
    // Kizz Daniel's first build had 43.
    expect(dropRefusal(43, 20)).toMatch(/53% drop/);
  });

  it("lets ordinary churn through on a small board", () => {
    // Yemi Alade's first build had 4 placements; 2 is a 50% fall and ordinary.
    expect(dropRefusal(4, 2)).toBeNull();
    // Oxlade 8 → 0: a small artist charting nowhere for an hour.
    expect(dropRefusal(8, 0)).toBeNull();
    // Stonebwoy 18 → 9: a 50% fall, but only 9 placements.
    expect(dropRefusal(18, 9)).toBeNull();
  });

  it("ignores growth and a missing previous file", () => {
    expect(dropRefusal(40, 60)).toBeNull();
    expect(dropRefusal(0, 12)).toBeNull();
  });

  it("gives every charting artist a real floor, and only the rest a zero", () => {
    for (const [slug, a] of Object.entries(LIVE_REGISTRY) as [string, { mayChartNowhere?: boolean; minPlacements?: number }][]) {
      if (a.minPlacements !== undefined) {
        expect(a.mayChartNowhere, `${slug} sets both a floor and mayChartNowhere`).not.toBe(true);
        expect(a.minPlacements, slug).toBeGreaterThan(0);
      }
    }
  });
});
